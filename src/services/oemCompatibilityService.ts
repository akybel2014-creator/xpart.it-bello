/**
 * Normalizza uno SKU fornito manualmente (uppercase alfanumerico + trattini/underscore).
 */
export function sanitizeSkuCode(raw: unknown): string {
  if (typeof raw !== "string") return "";
  return raw
    .trim()
    .toUpperCase()
    .replace(/[^A-Z0-9_-]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^[-_]+|[-_]+$/g, "")
    .slice(0, 48);
}

/**
 * Ricava un prefisso categoria leggibile di 3 caratteri (es. "Freni" -> "FRE",
 * "Componenti per la sovralimentazione" -> "SOV", fallback "RIC").
 */
export function deriveCategoryPrefix(categoryHint?: string | null): string {
  const cleaned = (categoryHint || "")
    .toUpperCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^A-Z0-9\s-]+/g, " ")
    .trim();

  if (!cleaned) return "RIC";

  const stopWords = new Set([
    "DI",
    "DA",
    "PER",
    "LA",
    "LE",
    "IL",
    "LO",
    "GLI",
    "DEL",
    "DELLA",
    "DELLE",
    "DEGLI",
    "CON",
    "COMPONENTI",
    "IMPIANTO",
    "SISTEMA",
    "ACCESSORI",
  ]);

  const tokens = cleaned
    .split(/[\s-]+/)
    .filter((tok) => tok.length >= 3 && !stopWords.has(tok));

  const primary = tokens[0] || cleaned.replace(/[^A-Z0-9]/g, "");
  const letters = primary.replace(/[^A-Z0-9]/g, "").slice(0, 3);
  return letters.length >= 2 ? letters : "RIC";
}

/**
 * Genera uno SKU deterministico, leggibile e privo di collisioni:
 * - Se `rawSku` è valido lo mantiene (aggiungendo suffisso progressivo solo in caso di collisione).
 * - Se assente/vuoto genera `<PREFISSO_CAT>-<OEM_NORM>-<PROGRESSIVO_3CIFRE>`.
 */
export function generateDeterministicSku(params: {
  rawSku?: string | null;
  categoryHint?: string | null;
  oemCode?: string | null;
  index?: number;
  usedSkus?: Set<string>;
}): { sku: string; generated: boolean } {
  const { rawSku, categoryHint, oemCode, index = 0, usedSkus } = params;
  const cleanedProvided = sanitizeSkuCode(rawSku);

  if (cleanedProvided.length >= 2) {
    let candidate = cleanedProvided;
    let suffix = 2;
    while (usedSkus?.has(candidate)) {
      candidate = `${cleanedProvided}-${String(suffix).padStart(2, "0")}`;
      suffix += 1;
    }
    usedSkus?.add(candidate);
    return { sku: candidate, generated: false };
  }

  const prefix = deriveCategoryPrefix(categoryHint);
  const normOem = normalizeOemCode(oemCode ?? "") || "OEM";
  const baseIndex = Number.isFinite(index) && index >= 0 ? Math.floor(index) + 1 : 1;

  let seq = baseIndex;
  let candidate = `${prefix}-${normOem}-${String(seq).padStart(3, "0")}`;
  while (usedSkus?.has(candidate)) {
    seq += 1;
    candidate = `${prefix}-${normOem}-${String(seq).padStart(3, "0")}`;
  }

  usedSkus?.add(candidate);
  return { sku: candidate, generated: true };
}

/**
 * Calcola uno SKU deterministico coerente per le schede ricambio del sito
 * (stesso output in card, modale dettaglio e risultati OEM).
 */
export function buildSitePartSku(params: {
  category?: string | null;
  oemCode?: string | null;
  fallbackId?: string | number | null;
}): string {
  const prefix = deriveCategoryPrefix(params.category);
  const normOem = normalizeOemCode(params.oemCode ?? "");
  const idDigits = String(params.fallbackId ?? "")
    .replace(/[^0-9]/g, "")
    .slice(-3);
  const suffix = idDigits ? idDigits.padStart(3, "0") : "001";
  if (normOem) {
    return `${prefix}-${normOem}-${suffix}`;
  }
  const cleanFallback = sanitizeSkuCode(String(params.fallbackId ?? ""));
  return cleanFallback || `${prefix}-SITE-${suffix}`;
}

function clampChunkSize(value: number | undefined, fallback: number): number {
  const num = Number(value);
  if (!Number.isFinite(num)) return fallback;
  return Math.max(20, Math.min(100, Math.floor(num)));
}

function splitIntoChunks<T>(items: T[], chunkSize: number): T[][] {
  if (!Array.isArray(items) || items.length === 0) return [];
  const chunks: T[][] = [];
  for (let i = 0; i < items.length; i += chunkSize) {
    chunks.push(items.slice(i, i + chunkSize));
  }
  return chunks;
}

function toPositiveIntegerId(value: unknown): number | null {
  if (typeof value === "number") {
    return Number.isSafeInteger(value) && value > 0 ? value : null;
  }
  if (typeof value === "string") {
    const cleaned = value.trim();
    if (!/^\d+$/.test(cleaned)) return null;
    const parsed = Number(cleaned);
    return Number.isSafeInteger(parsed) && parsed > 0 ? parsed : null;
  }
  return null;
}

function extractErrorCode(err: unknown): string | null {
  if (err && typeof err === "object" && "code" in err) {
    const code = (err as { code?: unknown }).code;
    return typeof code === "string" ? code : null;
  }
  return null;
}

function formatRpcErrorMessage(
  err: unknown,
  rpcName: string,
  defaultMessage: string
): string {
  const code = extractErrorCode(err);
  const rawMessage =
    err && typeof err === "object" && "message" in err
      ? String((err as { message?: unknown }).message ?? "")
      : err instanceof Error
        ? err.message
        : "";

  if (code === "42883" || code === "PGRST202") {
    return `La funzione RPC "public.${rpcName}" non risulta ancora presente su Supabase. Esegui lo script SQL e riprova.`;
  }
  if (
    code === "42501" ||
    rawMessage.toLowerCase().includes("permission denied") ||
    rawMessage.toLowerCase().includes("row-level security")
  ) {
    return `Permesso negato (RLS) sulla funzione "public.${rpcName}". Verifica di aver effettuato l'accesso autenticato o controlla le policy su "${OEM_COMPATIBILITY_TABLE}".`;
  }
  return rawMessage || defaultMessage;
}

/**
 * Esegue la verifica batch dei codici OEM tramite `public.match_oem_codes_batch`
 * in chunk da 50-100 codici normalizzati, mappando `matched_code_norm` sia per
 * abbinamenti verificati (`oem_vehicle_compatibility` + `vehicles`) sia per
 * suggerimenti di catalogo (`codici_oem_catalogo` su `oem_code` e `cross_reference`).
 */
export async function matchOemCodesBatch(
  codes: string[],
  options: MatchOemCodesBatchOptions = {}
): Promise<MatchOemCodesBatchResponse> {
  const {
    chunkSize = 75,
    client = defaultSupabase,
    signal,
    onProgress,
  } = options;

  const safeCodes = Array.isArray(codes) ? codes : [];
  const uniqueNormalized = Array.from(
    new Set(
      safeCodes
        .map((c) => normalizeOemCode(typeof c === "string" ? c : String(c ?? "")))
        .filter((c) => c.length > 0)
    )
  );

  const resultsByCode: Record<string, OemBatchMatchResult> = {};
  for (const norm of uniqueNormalized) {
    resultsByCode[norm] = {
      normalizedCode: norm,
      status: "da_abbinare",
      verifiedVehicles: [],
      catalogSuggestions: [],
    };
  }

  if (uniqueNormalized.length === 0) {
    return {
      resultsByCode,
      processedCount: 0,
      aborted: false,
      error: null,
      errorCode: null,
    };
  }

  if (!client) {
    return {
      resultsByCode,
      processedCount: 0,
      aborted: false,
      error:
        supabaseConfigError ||
        "Connessione Supabase non configurata nelle variabili d'ambiente.",
      errorCode: "NO_CLIENT",
    };
  }

  const effectiveChunkSize = clampChunkSize(chunkSize, 75);
  const chunks = splitIntoChunks(uniqueNormalized, effectiveChunkSize);
  let processedCount = 0;

  // Mappe di deduplicazione per ciascun codice normalizzato
  const seenVerifiedIds = new Map<string, Set<number>>();
  const seenSuggestionKeys = new Map<string, Set<string>>();

  for (let i = 0; i < chunks.length; i++) {
    if (signal?.aborted) {
      return {
        resultsByCode,
        processedCount,
        aborted: true,
        error: null,
        errorCode: null,
      };
    }

    const chunk = chunks[i];
    const { data, error } = await client.rpc(MATCH_OEM_CODES_RPC, {
      p_codes: chunk,
    });

    if (error) {
      logSupabaseError(
        `matchOemCodesBatch(chunk ${i + 1}/${chunks.length})`,
        MATCH_OEM_CODES_RPC,
        error
      );
      return {
        resultsByCode,
        processedCount,
        aborted: false,
        error: formatRpcErrorMessage(
          error,
          MATCH_OEM_CODES_RPC,
          "Errore durante la verifica dei codici OEM su Supabase."
        ),
        errorCode: extractErrorCode(error),
      };
    }

    const rows: MatchOemRpcRow[] = Array.isArray(data)
      ? (data as MatchOemRpcRow[])
      : [];

    for (const row of rows) {
      if (!row || typeof row !== "object") continue;

      const matchedKey = normalizeOemCode(
        row.matched_code_norm ?? row.catalog_oem_code ?? ""
      );
      if (!matchedKey) continue;

      if (!resultsByCode[matchedKey]) {
        resultsByCode[matchedKey] = {
          normalizedCode: matchedKey,
          status: "da_abbinare",
          verifiedVehicles: [],
          catalogSuggestions: [],
        };
      }

      const bucket = resultsByCode[matchedKey];
      const source = String(row.source ?? "").toLowerCase();
      const vehicleId = toPositiveIntegerId(row.vehicle_id);

      if (source === "verified" && vehicleId !== null) {
        let idSet = seenVerifiedIds.get(matchedKey);
        if (!idSet) {
          idSet = new Set<number>();
          seenVerifiedIds.set(matchedKey, idSet);
        }
        if (!idSet.has(vehicleId)) {
          idSet.add(vehicleId);
          bucket.verifiedVehicles.push({
            vehicle_id: vehicleId,
            marca: (row.marca ?? "").trim(),
            modello: (row.modello ?? "").trim(),
            versione: (row.versione ?? "").trim(),
            catalog_oem_code: (row.catalog_oem_code ?? matchedKey).trim(),
            verified: row.verified !== false,
          });
        }
      } else {
        const marca = (row.marca ?? "").trim();
        const modello = (row.modello ?? "").trim();
        const catalogOem = (row.catalog_oem_code ?? matchedKey).trim();
        const crossRef = row.cross_reference ? row.cross_reference.trim() : null;
        const fittingSide = row.fitting_side ? row.fitting_side.trim() : null;

        if (!marca && !modello) continue;

        let suggSet = seenSuggestionKeys.get(matchedKey);
        if (!suggSet) {
          suggSet = new Set<string>();
          seenSuggestionKeys.set(matchedKey, suggSet);
        }
        const suggKey = `${marca.toUpperCase()}|${modello.toUpperCase()}|${normalizeOemCode(catalogOem)}|${normalizeOemCode(crossRef ?? "")}`;
        if (!suggSet.has(suggKey)) {
          suggSet.add(suggKey);
          bucket.catalogSuggestions.push({
            marca,
            modello,
            catalog_oem_code: catalogOem,
            cross_reference: crossRef,
            fitting_side: fittingSide,
          });
        }
      }
    }

    processedCount += chunk.length;
    onProgress?.({
      processed: processedCount,
      total: uniqueNormalized.length,
      chunkIndex: i + 1,
      totalChunks: chunks.length,
    });

    // Cede un frame al main thread per evitare freeze UI su CSV grandi
    if (i < chunks.length - 1) {
      await new Promise<void>((resolve) => window.setTimeout(resolve, 0));
    }
  }

  // Classifica stato finale e ordina risultati in modo deterministico
  for (const key of Object.keys(resultsByCode)) {
    const entry = resultsByCode[key];
    entry.verifiedVehicles.sort((a, b) =>
      `${a.marca} ${a.modello} ${a.versione}`.localeCompare(
        `${b.marca} ${b.modello} ${b.versione}`,
        "it"
      )
    );
    entry.catalogSuggestions.sort((a, b) =>
      `${a.marca} ${a.modello}`.localeCompare(`${b.marca} ${b.modello}`, "it")
    );

    if (entry.verifiedVehicles.length > 0) {
      entry.status = "abbinato";
    } else if (entry.catalogSuggestions.length > 0) {
      entry.status = "suggerito";
    } else {
      entry.status = "da_abbinare";
    }
  }

  return {
    resultsByCode,
    processedCount,
    aborted: false,
    error: null,
    errorCode: null,
  };
}

/**
 * Salva in modo idempotente (a blocchi) gli abbinamenti OEM -> `public.vehicles.id`
 * tramite `public.upsert_oem_vehicle_links`.
 */
export async function upsertOemVehicleLinks(
  links: OemVehicleLinkPayload[],
  options: UpsertOemLinksOptions = {}
): Promise<UpsertOemLinksResponse> {
  const {
    chunkSize = 100,
    client = defaultSupabase,
    signal,
    onProgress,
  } = options;

  const safeLinks = Array.isArray(links) ? links : [];
  const dedupedMap = new Map<
    string,
    { oem_code: string; vehicle_id: number; source: string; notes?: string }
  >();

  for (const item of safeLinks) {
    if (!item || typeof item !== "object") continue;
    const rawCode = String(item.oem_code ?? "").trim();
    const normCode = normalizeOemCode(rawCode);
    const vehicleId = toPositiveIntegerId(item.vehicle_id);
    if (!normCode || vehicleId === null) continue;

    const dedupeKey = `${normCode}::${vehicleId}`;
    if (!dedupedMap.has(dedupeKey)) {
      dedupedMap.set(dedupeKey, {
        oem_code: rawCode,
        vehicle_id: vehicleId,
        source: (item.source ?? "seller_manual").trim() || "seller_manual",
        ...(item.notes?.trim() ? { notes: item.notes.trim() } : {}),
      });
    }
  }

  const sanitizedLinks = Array.from(dedupedMap.values());
  if (sanitizedLinks.length === 0) {
    return {
      savedCount: 0,
      processedChunks: 0,
      aborted: false,
      error: null,
      errorCode: null,
    };
  }

  if (!client) {
    return {
      savedCount: 0,
      processedChunks: 0,
      aborted: false,
      error:
        supabaseConfigError ||
        "Connessione Supabase non configurata nelle variabili d'ambiente.",
      errorCode: "NO_CLIENT",
    };
  }

  const effectiveChunkSize = clampChunkSize(chunkSize, 100);
  const chunks = splitIntoChunks(sanitizedLinks, effectiveChunkSize);
  let savedCount = 0;
  let processedItems = 0;

  for (let i = 0; i < chunks.length; i++) {
    if (signal?.aborted) {
      return {
        savedCount,
        processedChunks: i,
        aborted: true,
        error: null,
        errorCode: null,
      };
    }

    const chunk = chunks[i];
    const { data, error } = await client.rpc(UPSERT_OEM_LINKS_RPC, {
      p_links: chunk,
    });

    if (error) {
      const errCode = extractErrorCode(error);
      const errMsgLower = String(
        (error as { message?: unknown })?.message ?? ""
      ).toLowerCase();
      const isAuthSessionBlock =
        errCode === "P0001" ||
        errMsgLower.includes("sessione autenticata") ||
        errMsgLower.includes("accesso negato");

      // Fallback difensivo sul perimetro SITO (`public.oem_vehicle_compatibility`)
      // se la RPC in anteprima/test rifiuta il ruolo `anon` prima dell'aggiornamento SQL
      if (isAuthSessionBlock) {
        const directRows = chunk.map((item) => ({
          oem_code: item.oem_code,
          oem_code_norm: normalizeOemCode(item.oem_code),
          vehicle_id: item.vehicle_id,
          source: item.source,
          notes: item.notes ?? null,
          verified: true,
        }));

        const { data: directData, error: directError } = await client
          .from(OEM_COMPATIBILITY_TABLE)
          .upsert(directRows, {
            onConflict: "oem_code_norm,vehicle_id",
            ignoreDuplicates: false,
          })
          .select("vehicle_id");

        if (!directError) {
          savedCount += Array.isArray(directData)
            ? directData.length
            : chunk.length;
          processedItems += chunk.length;

          onProgress?.({
            processed: processedItems,
            total: sanitizedLinks.length,
            chunkIndex: i + 1,
            totalChunks: chunks.length,
          });

          if (i < chunks.length - 1) {
            await new Promise<void>((resolve) => window.setTimeout(resolve, 0));
          }
          continue;
        }

        logSupabaseError(
          `upsertOemVehicleLinks:fallback(chunk ${i + 1}/${chunks.length})`,
          OEM_COMPATIBILITY_TABLE,
          directError
        );

        return {
          savedCount,
          processedChunks: i,
          aborted: false,
          error:
            "La RPC public.upsert_oem_vehicle_links richiede ancora una sessione autenticata su Supabase. Esegui lo script SQL di aggiornamento SECURITY DEFINER + GRANT EXECUTE TO anon, authenticated e riprova.",
          errorCode: errCode || extractErrorCode(directError),
        };
      }

      logSupabaseError(
        `upsertOemVehicleLinks(chunk ${i + 1}/${chunks.length})`,
        UPSERT_OEM_LINKS_RPC,
        error
      );
      return {
        savedCount,
        processedChunks: i,
        aborted: false,
        error: formatRpcErrorMessage(
          error,
          UPSERT_OEM_LINKS_RPC,
          "Errore durante il salvataggio degli abbinamenti OEM su Supabase."
        ),
        errorCode: errCode,
      };
    }

    const numericCount = Number(data);
    savedCount += Number.isFinite(numericCount) ? numericCount : chunk.length;
    processedItems += chunk.length;

    onProgress?.({
      processed: processedItems,
      total: sanitizedLinks.length,
      chunkIndex: i + 1,
      totalChunks: chunks.length,
    });

    if (i < chunks.length - 1) {
      await new Promise<void>((resolve) => window.setTimeout(resolve, 0));
    }
  }

  return {
    savedCount,
    processedChunks: chunks.length,
    aborted: false,
    error: null,
    errorCode: null,
  };
}

/**
 * Rimuove un singolo abbinamento verificato `(oem_code_norm, vehicle_id)`
 * dalla tabella `public.oem_vehicle_compatibility` senza bloccare la UI.
 */
export async function deleteOemVehicleLink(
  oemCode: string,
  vehicleId: number,
  client: SupabaseClient | null = defaultSupabase
): Promise<DeleteOemLinkResponse> {
  const normCode = normalizeOemCode(oemCode);
  const validVehicleId = toPositiveIntegerId(vehicleId);

  if (!normCode || validVehicleId === null) {
    return {
      deleted: false,
      error: "Parametri codice OEM o ID veicolo non validi per la rimozione.",
      errorCode: "INVALID_PARAMS",
    };
  }

  if (!client) {
    return {
      deleted: false,
      error:
        supabaseConfigError ||
        "Connessione Supabase non configurata nelle variabili d'ambiente.",
      errorCode: "NO_CLIENT",
    };
  }

  const { error } = await client
    .from(OEM_COMPATIBILITY_TABLE)
    .delete()
    .eq("oem_code_norm", normCode)
    .eq("vehicle_id", validVehicleId);

  if (error) {
    logSupabaseError(
      `deleteOemVehicleLink(${normCode}, #${validVehicleId})`,
      OEM_COMPATIBILITY_TABLE,
      error
    );
    return {
      deleted: false,
      error: formatRpcErrorMessage(
        error,
        OEM_COMPATIBILITY_TABLE,
        "Impossibile rimuovere l'abbinamento veicolo da Supabase."
      ),
      errorCode: extractErrorCode(error),
    };
  }

  return {
    deleted: true,
    error: null,
    errorCode: null,
  };
}

/**
 * Divide una singola riga CSV rispettando eventuali campi racchiusi tra virgolette.
 */
function splitCsvLine(line: string, delimiter: string): string[] {
  const result: string[] = [];
  let current = "";
  let inQuotes = false;

  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === '"') {
      if (inQuotes && line[i + 1] === '"') {
        current += '"';
        i += 1;
      } else {
        inQuotes = !inQuotes;
      }
      continue;
    }
    if (ch === delimiter && !inQuotes) {
      result.push(current.trim());
      current = "";
      continue;
    }
    current += ch;
  }
  result.push(current.trim());
  return result;
}

function detectDelimiter(sampleLines: string[]): string {
  const candidates = [";", "\t", ","];
  let best = ";";
  let bestScore = 0;

  for (const delim of candidates) {
    let score = 0;
    for (const line of sampleLines.slice(0, 5)) {
      const count = line.split(delim).length - 1;
      if (count > 0) score += count;
    }
    if (score > bestScore) {
      bestScore = score;
      best = delim;
    }
  }

  return bestScore > 0 ? best : ";";
}

function normalizeHeaderName(raw: string): string {
  return (raw || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

/**
 * Analizza un file CSV o una lista di codici OEM incollati (1 per riga),
 * riconoscendo separatori (; , tab) e intestazioni comuni.
 */
export function parseOemCsvOrLines(rawText: string): ParseOemInputResult {
  const cleanedText = (rawText || "").replace(/^\uFEFF/, "");
  const lines = cleanedText
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line.length > 0);

  if (lines.length === 0) {
    return {
      rows: [],
      duplicatesSkipped: 0,
      invalidSkipped: 0,
      detectedDelimiter: ";",
    };
  }

  const delimiter = detectDelimiter(lines);
  const firstCols = splitCsvLine(lines[0], delimiter);
  const normalizedHeaders = firstCols.map(normalizeHeaderName);

  const OEM_HEADERS = new Set([
    "codice_oem",
    "codice_oe",
    "oem",
    "oem_code",
    "oe",
    "codice",
    "codice_ricambio",
    "codice_originale",
    "part_number",
    "ref",
  ]);
  const SKU_HEADERS = new Set([
    "sku",
    "codice_sku",
    "codice_interno",
    "codice_articolo",
    "internal_sku",
    "sku_univoco",
  ]);
  const LABEL_HEADERS = new Set([
    "descrizione",
    "titolo",
    "nome",
    "ricambio",
    "articolo",
    "description",
    "title",
  ]);
  const CATEGORY_HEADERS = new Set([
    "categoria",
    "categoria_slug",
    "category",
    "gruppo",
  ]);
  const BRAND_HEADERS = new Set(["marca", "brand", "car_brand", "costruttore"]);
  const MODEL_HEADERS = new Set(["modello", "model", "car_model"]);
  const COMPAT_HEADERS = new Set([
    "compatibilita_veicoli",
    "veicoli_compatibili",
    "compatibilita",
    "auto_compatibili",
    "veicoli",
    "vehicle_compatibility",
    "compatibility",
  ]);
  const NOTES_HEADERS = new Set(["note", "notes", "annotazioni"]);

  let oemIdx = normalizedHeaders.findIndex((h) => OEM_HEADERS.has(h));
  const skuIdx = normalizedHeaders.findIndex((h) => SKU_HEADERS.has(h));
  const labelIdx = normalizedHeaders.findIndex((h) => LABEL_HEADERS.has(h));
  const categoryIdx = normalizedHeaders.findIndex((h) => CATEGORY_HEADERS.has(h));
  const brandIdx = normalizedHeaders.findIndex((h) => BRAND_HEADERS.has(h));
  const modelIdx = normalizedHeaders.findIndex((h) => MODEL_HEADERS.has(h));
  const compatIdx = normalizedHeaders.findIndex((h) => COMPAT_HEADERS.has(h));
  const notesIdx = normalizedHeaders.findIndex((h) => NOTES_HEADERS.has(h));

  const hasHeaderRow =
    oemIdx !== -1 ||
    skuIdx !== -1 ||
    labelIdx !== -1 ||
    brandIdx !== -1 ||
    modelIdx !== -1 ||
    compatIdx !== -1 ||
    categoryIdx !== -1;

  if (oemIdx === -1) {
    // Se manca un'intestazione OEM esplicita, usa la prima colonna disponibile diversa da `sku`
    oemIdx = skuIdx === 0 && firstCols.length > 1 ? 1 : 0;
  }

  const startIndex = hasHeaderRow ? 1 : 0;
  const rows: ParsedCsvOemRow[] = [];
  const seenNorm = new Set<string>();
  const usedSkus = new Set<string>();
  let duplicatesSkipped = 0;
  let invalidSkipped = 0;

  for (let i = startIndex; i < lines.length; i++) {
    const cols = splitCsvLine(lines[i], delimiter);
    const rawCode = (cols[oemIdx] ?? "").trim();
    const normalizedCode = normalizeOemCode(rawCode);

    if (normalizedCode.length < 2) {
      invalidSkipped += 1;
      continue;
    }

    if (seenNorm.has(normalizedCode)) {
      duplicatesSkipped += 1;
      continue;
    }
    seenNorm.add(normalizedCode);

    const fallbackLabel = !hasHeaderRow && cols.length > 1 ? cols[1] ?? "" : "";
    const categoryHint = (categoryIdx !== -1 ? cols[categoryIdx] : "")?.trim() ?? "";
    const rawSku = (skuIdx !== -1 ? cols[skuIdx] : "")?.trim() ?? "";
    const { sku, generated: skuAutoGenerated } = generateDeterministicSku({
      rawSku,
      categoryHint,
      oemCode: normalizedCode,
      index: rows.length,
      usedSkus,
    });

    rows.push({
      rowId: `oem-row-${i}-${normalizedCode}`,
      sku,
      skuAutoGenerated,
      rawCode,
      normalizedCode,
      label: (labelIdx !== -1 ? cols[labelIdx] : fallbackLabel)?.trim() ?? "",
      categoryHint,
      brandHint: (brandIdx !== -1 ? cols[brandIdx] : "")?.trim() ?? "",
      modelHint: (modelIdx !== -1 ? cols[modelIdx] : "")?.trim() ?? "",
      compatibilityNote: (compatIdx !== -1 ? cols[compatIdx] : "")?.trim() ?? "",
      notes: (notesIdx !== -1 ? cols[notesIdx] : "")?.trim() ?? "",
    });
  }

  return {
    rows,
    duplicatesSkipped,
    invalidSkipped,
    detectedDelimiter: delimiter,
  };
}

